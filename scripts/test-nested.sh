#!/usr/bin/env bash
# Opt-in nested testing. Never sends IPC to the host Hyprland instance.
set -euo pipefail

usage() {
    cat <<'EOF'
Usage: scripts/test-nested.sh MODE PLUGIN.so|--baseline
  --prepare          Save config, plugin snapshot and launch command only.
  --check-isolation  Check namespace isolation; do not start a compositor.
  --run              Start a nested Hyprland, limited to 180 seconds.

Requires Linux bubblewrap, Hyprland 0.57 Lua config support, dbus-run-session,
and an existing Wayland display. Only --run starts a compositor.
Logs and the exact plugin snapshot are kept in .build/nested/run.*.
This shares the host kernel, render devices and parent Wayland server.
Use a VM without GPU passthrough when those must also be isolated.
EOF
}

[[ $# == 2 ]] || { usage; exit 2; }
mode=$1
case "$mode" in
    --prepare|--check-isolation|--run) ;;
    *) usage; exit 2 ;;
esac
for tool in bwrap Hyprland dbus-run-session timeout sha256sum; do
    command -v "$tool" >/dev/null || { echo "Missing: $tool" >&2; exit 1; }
done
[[ -n ${XDG_RUNTIME_DIR:-} && -n ${WAYLAND_DISPLAY:-} ]] || {
    echo 'No parent Wayland display; refusing to start.' >&2
    exit 1
}
case "$WAYLAND_DISPLAY" in
    /*) parent_socket=$WAYLAND_DISPLAY ;;
    *) parent_socket=$XDG_RUNTIME_DIR/$WAYLAND_DISPLAY ;;
esac
[[ -S "$parent_socket" ]] || { echo 'Parent socket not found.' >&2; exit 1; }

root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
plugin=
if [[ $2 != --baseline ]]; then
    plugin=$(realpath -- "$2")
    [[ -f "$plugin" && -r "$plugin" ]] || {
        echo 'Plugin must be a readable file.' >&2; exit 1;
    }
fi
umask 077
mkdir -p "$root/.build/nested"
work=$(mktemp -d "$root/.build/nested/run.XXXXXXXX")
mkdir -p "$work"/{home,config,cache,state,data,runtime}
Hyprland --version >"$work/version.txt" 2>&1
if [[ -n "$plugin" ]]; then
    cp -- "$plugin" "$work/plugin.so"
    sha256sum "$work/plugin.so" >"$work/plugin.sha256"
fi
cat >"$work/hyprland.lua" <<'EOF'
hl.monitor({output = "", mode = "1280x720@60", position = "auto", scale = 1})
hl.config({
    autogenerated = false,
    xwayland = {enabled = false},
    ecosystem = {no_update_news = true, no_donation_nag = true},
    misc = {disable_hyprland_logo = true, disable_splash_rendering = true},
    debug = {disable_logs = false},
})
-- No host config, autostart, hyprpm, portal or environment import.
-- ALT bindings avoid the usual host SUPER bindings where possible.
hl.bind("ALT + Escape", function() hl.dispatch(hl.dsp.exit()) end)
hl.bind("ALT + Return", function() hl.exec_cmd("kitty") end)
EOF
if [[ -n "$plugin" ]]; then
    cat >>"$work/hyprland.lua" <<'EOF'
hl.plugin.load("/test/plugin.so")
hl.bind("ALT + g", function()
    hl.plugin.scrolloverview.overview("toggle all")
end)
hl.bind("ALT + f", function()
    hl.plugin.scrolloverview.search("open")
end)
EOF
fi

uid=$(id -u)
# A fresh /dev and /run prevent fallback to a physical seat or host IPC.
# Render nodes cannot perform modesetting. No card*, input, tty or host bus.
command=(bwrap --unshare-all --die-with-parent --new-session --cap-drop ALL
    --ro-bind /usr /usr --ro-bind /etc /etc
    --symlink usr/bin /bin --symlink usr/bin /sbin
    --symlink usr/lib /lib --symlink usr/lib /lib64
    --proc /proc --dev /dev --tmpfs /tmp --tmpfs /run
    --ro-bind /sys /sys
    --bind "$work" /test --bind "$work/home" /home/test
    --dir /run/user --bind "$work/runtime" "/run/user/$uid"
    --ro-bind "$parent_socket" /run/parent-wayland
    --clearenv --setenv PATH /usr/bin:/bin
    --setenv HOME /home/test --setenv USER test --setenv LOGNAME test
    --setenv LANG C.UTF-8 --setenv XDG_RUNTIME_DIR "/run/user/$uid"
    --setenv XDG_CONFIG_HOME /test/config --setenv XDG_CACHE_HOME /test/cache
    --setenv XDG_STATE_HOME /test/state --setenv XDG_DATA_HOME /test/data
    --setenv WAYLAND_DISPLAY /run/parent-wayland
    --setenv LIBSEAT_BACKEND seatd --setenv SEATD_SOCK /run/no-seatd.sock
    --setenv HYPRLAND_NO_SD_VARS 1 --setenv HYPRLAND_NO_SD_NOTIFY 1
    --setenv HYPRLAND_NO_SD_TARGET 1 --setenv HYPRLAND_NO_RT 1
    --chdir /test)
shopt -s nullglob
render_nodes=(/dev/dri/renderD*)
if ((${#render_nodes[@]})); then
    command+=(--dir /dev/dri)
    for node in "${render_nodes[@]}"; do
        command+=(--dev-bind "$node" "$node")
    done
fi
launch=(timeout --signal=TERM --kill-after=5s 180s
    dbus-run-session -- Hyprland --config /test/hyprland.lua)
printf '%q ' "${command[@]}" -- "${launch[@]}" >"$work/command.txt"
printf '\n' >>"$work/command.txt"
printf 'Artifacts: %s\n' "$work"
case "$mode" in
    --prepare)
        echo 'Prepared only; no namespace or compositor started.'
        ;;
    --check-isolation)
        "${command[@]}" -- /bin/sh -eu -c '
            test -z "${HYPRLAND_INSTANCE_SIGNATURE:-}"
            test -z "${DBUS_SESSION_BUS_ADDRESS:-}"
            test ! -e /run/dbus/system_bus_socket
            test ! -e "$XDG_RUNTIME_DIR/bus"
            test ! -e "$XDG_RUNTIME_DIR/hypr"
            test ! -e /dev/input
            test ! -e /dev/tty0
            for card in /dev/dri/card*; do test ! -e "$card"; done
            test -S "$WAYLAND_DISPLAY"
            test "$HYPRLAND_NO_SD_VARS" = 1
            test "$HYPRLAND_NO_SD_NOTIFY" = 1
            test "$HYPRLAND_NO_SD_TARGET" = 1
            test "$LIBSEAT_BACKEND" = seatd
            test ! -e "$SEATD_SOCK"
            Hyprland --version
            echo "Namespace checks passed; no compositor started."
        ' 2>&1 | tee "$work/isolation.log"
        ;;
    --run)
        echo 'Starting nested test only; ALT+Escape exits. Timeout: 180 seconds.'
        echo 'A rendering failure is not permission to fall back to the host.'
        "${command[@]}" -- "${launch[@]}" 2>&1 | tee "$work/session.log"
        ;;
esac
